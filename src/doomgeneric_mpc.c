#define SCR_W 320
#define SCR_H 240
#define GAME_W DOOMGENERIC_RESX
#define GAME_H DOOMGENERIC_RESY
#define GAME_Y ((SCR_H - GAME_H) / 2)

/* keys that nothing else in the game uses, bound to the menu/weapon actions in DG_Init */
#define K_MENU_UP    0xB0
#define K_MENU_DOWN  0xB1
#define K_NEXTWEAPON 0xB2
#define K_PREVWEAPON 0xB3

/* one DATA encoder detent = this much mouse x; angle = x * 8 / 65536 * 360 deg (~8.8 deg) */
#define TURN_PER_DETENT 200

static void logm(const char *fmt, ...)
{
    va_list ap; va_start(ap, fmt);
    fputs("mpcdoom: ", stderr); vfprintf(stderr, fmt, ap); fputc('\n', stderr);
    va_end(ap);
}

/* ------------------------------------------------------------------ time ---- */
static struct timespec t0;

uint32_t DG_GetTicksMs(void)
{
    struct timespec t; clock_gettime(CLOCK_MONOTONIC, &t);
    return (uint32_t)((t.tv_sec - t0.tv_sec) * 1000 + (t.tv_nsec - t0.tv_nsec) / 1000000);
}

void DG_SleepMs(uint32_t ms)
{
    struct timespec t = { ms / 1000, (long)(ms % 1000) * 1000000L };
    while (nanosleep(&t, &t) < 0 && errno == EINTR) {}
}

/* ---------------------------------------------------------------- screen ---- */
static int drm_fd = -1;
static uint32_t fb_id, crtc_id, conn_id, dumb_handle;
static uint8_t *scanout;
static uint32_t scan_pitch;
static uint64_t scan_size;
static uint32_t frame[GAME_W * GAME_H];            /* latest frame from the game thread */
static pthread_mutex_t fl_lock = PTHREAD_MUTEX_INITIALIZER;
static pthread_cond_t fl_cond = PTHREAD_COND_INITIALIZER;
static int fl_pending, fl_quit, fl_started;
static pthread_t fl_thread;
static unsigned stat_rendered, stat_flushed, stat_replaced;

static int drm_call(unsigned long req, void *arg, const char *what)
{
    int r;
    while ((r = ioctl(drm_fd, req, arg)) < 0 && errno == EINTR) {}
    if (r < 0) logm("drm %s: %s", what, strerror(errno));
    return r;
}

static void drm_dirty(int x1, int y1, int x2, int y2)
{
    struct mpc_drm_clip_rect clip = { (uint16_t)x1, (uint16_t)y1, (uint16_t)x2, (uint16_t)y2 };
    struct mpc_drm_fb_dirty_cmd cmd = { fb_id, 0, 0, 1, (uint64_t)(uintptr_t)&clip };
    drm_call(MPC_DRM_IOCTL_MODE_DIRTYFB, &cmd, "dirtyfb");
}

static int screen_open(void)
{
    drm_fd = open("/dev/dri/card0", O_RDWR | O_CLOEXEC);
    if (drm_fd < 0) { logm("/dev/dri/card0: %s", strerror(errno)); return -1; }
    if (ioctl(drm_fd, MPC_DRM_IOCTL_SET_MASTER, 0) < 0) {
        logm("drm set master: %s%s", strerror(errno), errno == EACCES ? " (is ac50.service still running?)" : "");
        return -1;
    }
    uint32_t crtcs[4] = {0}, conns[4] = {0};
    struct mpc_drm_card_res res = { 0, (uint64_t)(uintptr_t)crtcs, (uint64_t)(uintptr_t)conns, 0, 0, 4, 4, 0, 0, 0, 0, 0 };
    if (drm_call(MPC_DRM_IOCTL_MODE_GETRESOURCES, &res, "getresources") < 0) return -1;
    if (!res.count_crtcs || !res.count_connectors) { logm("drm: no crtc/connector"); return -1; }
    crtc_id = crtcs[0]; conn_id = conns[0];
    struct mpc_drm_get_connector con; memset(&con, 0, sizeof con); con.connector_id = conn_id;
    if (drm_call(MPC_DRM_IOCTL_MODE_GETCONNECTOR, &con, "getconnector") < 0) return -1;
    if (!con.count_modes) { logm("drm: connector has no modes"); return -1; }
    uint32_t nmodes = con.count_modes;                 /* 1 on the device, dozens in QEMU */
    struct mpc_drm_modeinfo *modes = calloc(nmodes, sizeof *modes);
    memset(&con, 0, sizeof con); con.connector_id = conn_id; con.modes_ptr = (uint64_t)(uintptr_t)modes; con.count_modes = nmodes;
    if (drm_call(MPC_DRM_IOCTL_MODE_GETCONNECTOR, &con, "getconnector modes") < 0) return -1;
    struct mpc_drm_modeinfo mode = modes[0];
    for (uint32_t i = 0; i < nmodes; i++) if (modes[i].hdisplay == SCR_W && modes[i].vdisplay == SCR_H) { mode = modes[i]; break; }
    free(modes);
    if (mode.hdisplay != SCR_W || mode.vdisplay != SCR_H) { logm("drm: no %dx%d mode (%u modes, first %ux%u)", SCR_W, SCR_H, nmodes, mode.hdisplay, mode.vdisplay); return -1; }
    struct mpc_drm_create_dumb dumb = { SCR_H, SCR_W, 32, 0, 0, 0, 0 };
    if (drm_call(MPC_DRM_IOCTL_MODE_CREATE_DUMB, &dumb, "create dumb") < 0) return -1;
    dumb_handle = dumb.handle; scan_pitch = dumb.pitch; scan_size = dumb.size;
    struct mpc_drm_fb_cmd2 add; memset(&add, 0, sizeof add);
    add.width = SCR_W; add.height = SCR_H; add.pixel_format = MPC_DRM_FORMAT_XRGB8888;
    add.handles[0] = dumb.handle; add.pitches[0] = dumb.pitch;
    if (drm_call(MPC_DRM_IOCTL_MODE_ADDFB2, &add, "addfb2") < 0) return -1;
    fb_id = add.fb_id;
    struct mpc_drm_map_dumb map = { dumb.handle, 0, 0 };
    if (drm_call(MPC_DRM_IOCTL_MODE_MAP_DUMB, &map, "map dumb") < 0) return -1;
    void *p = mmap(NULL, scan_size, PROT_READ | PROT_WRITE, MAP_SHARED, drm_fd, (off_t)map.offset);
    if (p == MAP_FAILED) { logm("mmap dumb: %s", strerror(errno)); return -1; }
    scanout = p;
    memset(scanout, 0, scan_size);
    struct mpc_drm_crtc set; memset(&set, 0, sizeof set);
    set.set_connectors_ptr = (uint64_t)(uintptr_t)&conn_id; set.count_connectors = 1;
    set.crtc_id = crtc_id; set.fb_id = fb_id; set.mode = mode; set.mode_valid = 1;
    if (drm_call(MPC_DRM_IOCTL_MODE_SETCRTC, &set, "setcrtc") < 0) return -1;
    drm_dirty(0, 0, SCR_W, SCR_H);
    logm("drm %ux%u crtc %u connector %u fb %u pitch %u", mode.hdisplay, mode.vdisplay, crtc_id, conn_id, fb_id, scan_pitch);
    return 0;
}

/* Boot splash: shown as soon as the panel is ours, while the engine loads the WAD. The text
 * is a 1-bit bitmap generated by tools/mksplash.py, one colour per line. It stays up for at
 * least SPLASH_MIN_MS (MPCDOOM_SPLASH_MS overrides) before the first game frame replaces it. */
#define SPLASH_MIN_MS 2500
static uint32_t splash_shown_ms;
static int splash_done;

static void splash_show(void)
{
    static const uint32_t line_rgb[SPLASH_LINES] = { 0xD41C1C, 0xE8E8E8, 0x8C8C8C };
    memset(scanout, 0, scan_size);
    for (int y = 0; y < SPLASH_H; y++) {
        int line = 0;
        while (line < SPLASH_LINES - 1 && y >= splash_line_end[line]) line++;
        uint32_t *row = (uint32_t *)(scanout + (size_t)(SPLASH_Y0 + y) * scan_pitch);
        for (int x = 0; x < SCR_W; x++)
            if (splash_bits[y][x >> 3] & (0x80 >> (x & 7))) row[x] = line_rgb[line];
    }
    drm_dirty(0, 0, SCR_W, SCR_H);
    splash_shown_ms = DG_GetTicksMs();
}

static void splash_finish(void)
{
    uint32_t min_ms = SPLASH_MIN_MS;
    const char *e = getenv("MPCDOOM_SPLASH_MS");
    if (e && *e) min_ms = (uint32_t)atoi(e);
    uint32_t shown = DG_GetTicksMs() - splash_shown_ms;
    if (shown < min_ms) DG_SleepMs(min_ms - shown);
    memset(scanout, 0, scan_size);          /* the game only ever repaints rows GAME_Y..GAME_Y+GAME_H */
    drm_dirty(0, 0, SCR_W, SCR_H);
    splash_done = 1;
}

static void *flush_thread(void *arg)
{
    (void)arg;
    for (;;) {
        pthread_mutex_lock(&fl_lock);
        while (!fl_pending && !fl_quit) pthread_cond_wait(&fl_cond, &fl_lock);
        if (fl_quit) { pthread_mutex_unlock(&fl_lock); break; }
        fl_pending = 0;
        for (int y = 0; y < GAME_H; y++)
            memcpy(scanout + (size_t)(GAME_Y + y) * scan_pitch, frame + (size_t)y * GAME_W, GAME_W * 4);
        pthread_mutex_unlock(&fl_lock);
        drm_dirty(0, GAME_Y, SCR_W, GAME_Y + GAME_H);     /* the slow part: SPI transfer on hardware */
        __atomic_fetch_add(&stat_flushed, 1, __ATOMIC_RELAXED);
    }
    return NULL;
}

static void screen_close(void)
{
    if (fl_started) {
        pthread_mutex_lock(&fl_lock); fl_quit = 1; pthread_cond_signal(&fl_cond); pthread_mutex_unlock(&fl_lock);
        pthread_join(fl_thread, NULL);
        fl_started = 0;
    }
    if (scanout) { memset(scanout, 0, scan_size); drm_dirty(0, 0, SCR_W, SCR_H); munmap(scanout, scan_size); scanout = NULL; }
    if (drm_fd >= 0) {
        if (fb_id) { uint32_t id = fb_id; ioctl(drm_fd, MPC_DRM_IOCTL_MODE_RMFB, &id); }
        if (dumb_handle) { struct mpc_drm_destroy_dumb d = { dumb_handle }; ioctl(drm_fd, MPC_DRM_IOCTL_MODE_DESTROY_DUMB, &d); }
        ioctl(drm_fd, MPC_DRM_IOCTL_DROP_MASTER, 0);
        close(drm_fd); drm_fd = -1;          /* ac50 sets its own mode when it restarts */
    }
}

/* ------------------------------------------------------------ pad LEDs ---- */
static int midi_fd = -1;
static uint8_t led_sent[16][3];
static int led_valid;

static void led_send(int pad, int r, int g, int b)
{
    uint8_t sx[12] = { 0xF0, 0x47, 0x7F, 0x5C, 0x65, 0x00, 0x04, (uint8_t)pad, (uint8_t)(r & 0x7F), (uint8_t)(g & 0x7F), (uint8_t)(b & 0x7F), 0xF7 };
    if (midi_fd >= 0 && write(midi_fd, sx, sizeof sx) < 0) {}
}

static void leds_show(const uint8_t want[16][3])
{
    for (int i = 0; i < 16; i++) {
        if (led_valid && !memcmp(led_sent[i], want[i], 3)) continue;
        led_send(i, want[i][0], want[i][1], want[i][2]);
        memcpy(led_sent[i], want[i], 3);
    }
    led_valid = 1;
}

/* pads 1-4 movement (blue), 5 fire (red), 6 use (green), 7 run (yellow), 8 weapon (purple);
 * pads 9-16: health, one pad per 12.5%, green > yellow > red; dim when not in a level */
static void leds_update(int health)
{
    static int last_health = -2;
    if (health == last_health && led_valid) return;
    last_health = health;
    uint8_t want[16][3] = {
        { 0, 20, 127 }, { 0, 20, 127 }, { 0, 40, 127 }, { 0, 20, 127 },
        { 127, 0, 0 }, { 0, 127, 0 }, { 127, 100, 0 }, { 90, 0, 127 },
    };
    int lit = health < 0 ? 0 : (health * 8 + 99) / 100;
    if (lit > 8) lit = 8;
    for (int i = 0; i < 8; i++) {
        uint8_t *w = want[8 + i];
        if (i < lit) {
            if (health > 66) { w[0] = 0; w[1] = 110; w[2] = 0; }
            else if (health > 33) { w[0] = 120; w[1] = 90; w[2] = 0; }
            else { w[0] = 127; w[1] = 0; w[2] = 0; }
        } else { w[0] = 3; w[1] = 3; w[2] = 5; }
    }
    leds_show(want);
}

static void leds_off(void)
{
    if (midi_fd < 0) return;
    for (int i = 0; i < 16; i++) led_send(i, 0, 0, 0);
}

/* ----------------------------------------------------------------- input ---- */
#define KQ_SIZE 256
static uint16_t kq[KQ_SIZE];                       /* (pressed << 8) | key, single producer / single consumer */
static _Atomic unsigned kq_w, kq_r;
static _Atomic int turn_accum;                     /* DATA encoder detents since the last tic */
static _Atomic int quit_req;
static int shift_held;
static pthread_t in_thread;

static const int pad_note[16] = { 37, 36, 42, 82, 40, 38, 46, 44, 48, 47, 45, 43, 49, 55, 51, 53 };
static const unsigned char pad_key[16] = {
    KEY_STRAFE_L, KEY_DOWNARROW, KEY_UPARROW, KEY_STRAFE_R,      /* PAD 1..4, bottom row */
    KEY_FIRE, KEY_USE, KEY_RSHIFT, K_NEXTWEAPON,                 /* PAD 5..8 */
    0, 0, 0, 0, 0, 0, 0, 0,                                      /* PAD 9..16: health display */
};

enum { BTN_SHIFT = 49, BTN_TAP = 53, BTN_PLUS = 54, BTN_MINUS = 55, BTN_STOP = 81, BTN_PLAY = 82, BTN_DATA = 111 };
enum { CC_DATA = 100 };

static void kq_push(int pressed, unsigned char key)
{
    unsigned w = atomic_load_explicit(&kq_w, memory_order_relaxed);
    if (w - atomic_load_explicit(&kq_r, memory_order_acquire) >= KQ_SIZE) return;   /* full: drop */
    kq[w % KQ_SIZE] = (uint16_t)((pressed << 8) | key);
    atomic_store_explicit(&kq_w, w + 1, memory_order_release);
}

static unsigned char button_key(int note)
{
    switch (note) {
    case BTN_SHIFT: return KEY_ESCAPE;
    case BTN_TAP:   return KEY_TAB;
    case BTN_PLUS:  return K_MENU_DOWN;
    case BTN_MINUS: return K_MENU_UP;
    case BTN_DATA:  return KEY_ENTER;
    case BTN_PLAY:  return 'y';
    case BTN_STOP:  return 'n';
    default: return 0;
    }
}

static int debug_input;

static void cs_message(const uint8_t *m, int len)
{
    int st = m[0] & 0xF0, ch = m[0] & 0x0F;
    if (debug_input) logm("cs: %02X %02X %02X", m[0], len > 1 ? m[1] : 0, len > 2 ? m[2] : 0);
    if (len != 3) return;
    if (ch == 9 && (st == 0x90 || st == 0x80)) {                  /* pads */
        int on = st == 0x90 && m[2] > 0;
        for (int i = 0; i < 16; i++)
            if (pad_note[i] == m[1] && pad_key[i]) { kq_push(on, pad_key[i]); break; }
    } else if (ch == 0 && (st == 0x90 || st == 0x80)) {           /* buttons */
        int on = st == 0x90 && m[2] > 0, note = m[1];
        if (note == BTN_SHIFT) shift_held = on;
        if (note == BTN_STOP && on && shift_held) { atomic_store(&quit_req, 1); return; }
        unsigned char k = button_key(note);
        if (k) kq_push(on, k);
    } else if (ch == 0 && st == 0xB0 && m[1] == CC_DATA) {        /* DATA encoder, relative */
        int v = m[2], d = v < 64 ? v : v - 128;
        atomic_fetch_add(&turn_accum, d);
    }
}

static int msg_len(uint8_t status)
{
    switch (status & 0xF0) { case 0xC0: case 0xD0: return 2; case 0x80: case 0x90: case 0xA0: case 0xB0: case 0xE0: return 3; default: return 1; }
}

static void *input_thread(void *arg)
{
    (void)arg;
    uint8_t buf[256], msg[3]; int n = 0, need = 0, in_sysex = 0;
    for (;;) {
        ssize_t r = read(midi_fd, buf, sizeof buf);
        if (r < 0) { if (errno == EINTR) continue; logm("midi read: %s", strerror(errno)); break; }
        if (r == 0) break;
        if (debug_input) { char hx[3 * 24 + 1]; int k = 0; for (ssize_t i = 0; i < r && i < 24; i++) k += snprintf(hx + k, sizeof hx - k, "%02X ", buf[i]); logm("read %zd: %s", r, hx); }
        for (ssize_t i = 0; i < r; i++) {
            uint8_t b = buf[i];
            if (b >= 0xF8) continue;                                   /* realtime */
            if (in_sysex) { if (b == 0xF7) in_sysex = 0; continue; }
            if (b == 0xF0) { in_sysex = 1; n = 0; continue; }
            if (b & 0x80) { msg[0] = b; n = 1; need = msg_len(b); if (need == 1) n = 0; continue; }
            if (n == 0) continue;                                      /* running status not expected from the MCU */
            msg[n++] = b;
            if (n == need) { cs_message(msg, n); n = 1; }             /* keep status for running status anyway */
        }
    }
    return NULL;
}

static int find_surface_midi(char *path, size_t n)
{
    for (int c = 0; c < 8; c++) {
        char p[64], id[64] = {0};
        snprintf(p, sizeof p, "/proc/asound/card%d/id", c);
        FILE *f = fopen(p, "r"); if (!f) continue;
        if (!fgets(id, sizeof id, f)) id[0] = 0;
        fclose(f);
        if (strcasestr(id, "surface")) { snprintf(path, n, "/dev/snd/midiC%dD0", c); return 0; }
    }
    return -1;
}

static void input_open(void)
{
    char path[64];
    if (find_surface_midi(path, sizeof path) < 0) { logm("no control surface MIDI device found; running without input"); return; }
    midi_fd = open(path, O_RDWR | O_CLOEXEC);
    if (midi_fd < 0) { logm("%s: %s", path, strerror(errno)); return; }
    /* The stock app opens the surface with timestamp framing (snd_rawmidi_tread) and the kernel
     * keeps that per-substream setting after it closes, so a plain read() would get 32-byte
     * snd_rawmidi_framing_tstamp frames. Set our own params: no framing, byte-at-a-time. */
    struct snd_rawmidi_params prm; memset(&prm, 0, sizeof prm);
    prm.stream = SNDRV_RAWMIDI_STREAM_INPUT; prm.buffer_size = 4096; prm.avail_min = 1; prm.mode = 0;
    if (ioctl(midi_fd, SNDRV_RAWMIDI_IOCTL_PARAMS, &prm) < 0) logm("rawmidi params: %s", strerror(errno));
    logm("control surface: %s", path);
    pthread_create(&in_thread, NULL, input_thread, NULL);
}

static void on_signal(int sig) { (void)sig; atomic_store(&quit_req, 1); }

/* ---------------------------------------------------- doomgeneric hooks ---- */
static void post_key(int key)
{
    event_t ev; memset(&ev, 0, sizeof ev);
    ev.type = ev_keydown; ev.data1 = key; D_PostEvent(&ev);
    ev.type = ev_keyup; D_PostEvent(&ev);
}

int DG_GetKey(int *pressed, unsigned char *key)
{
    static int turn_done;
    if (atomic_exchange(&quit_req, 0)) { logm("quit requested"); I_Quit(); }
    if (!turn_done) {
        turn_done = 1;
        int t = atomic_exchange(&turn_accum, 0);
        if (t) {
            if (menuactive) { for (int i = 0; i < (t < 0 ? -t : t); i++) post_key(t < 0 ? K_MENU_UP : K_MENU_DOWN); }
            else { event_t ev; memset(&ev, 0, sizeof ev); ev.type = ev_mouse; ev.data2 = t * TURN_PER_DETENT; D_PostEvent(&ev); }
        }
    }
    unsigned r = atomic_load_explicit(&kq_r, memory_order_relaxed);
    if (r == atomic_load_explicit(&kq_w, memory_order_acquire)) { turn_done = 0; return 0; }
    uint16_t k = kq[r % KQ_SIZE];
    atomic_store_explicit(&kq_r, r + 1, memory_order_release);
    *pressed = k >> 8; *key = (unsigned char)k;
    if (debug_input) logm("key %s 0x%02X", *pressed ? "down" : "up", *key);
    return 1;
}

void DG_Init(void)
{
    clock_gettime(CLOCK_MONOTONIC, &t0);
    { const char *e = getenv("MPCDOOM_DEBUG"); debug_input = e && *e; }
    signal(SIGTERM, on_signal); signal(SIGINT, on_signal); signal(SIGHUP, on_signal);
    if (screen_open() < 0) { screen_close(); exit(1); }
    splash_show();
    pthread_create(&fl_thread, NULL, flush_thread, NULL); fl_started = 1;
    input_open();
    atexit(leds_off);
    atexit(screen_close);
    key_menu_up = K_MENU_UP; key_menu_down = K_MENU_DOWN;
    key_nextweapon = K_NEXTWEAPON; key_prevweapon = K_PREVWEAPON;
    leds_update(-1);
}

void DG_DrawFrame(void)
{
    /* The engine redraws every loop iteration, more often than it runs tics, so identical
     * frames are common (title screen, menus, waiting for a tic): don't push those at all.
     * On the real panel every flush is an SPI transfer; in QEMU it is free. */
    if (!splash_done) splash_finish();     /* first frame: the flush thread has not touched the panel yet */
    pthread_mutex_lock(&fl_lock);
    if (memcmp(frame, DG_ScreenBuffer, sizeof frame) != 0) {
        memcpy(frame, DG_ScreenBuffer, sizeof frame);
        if (fl_pending) stat_replaced++;
        fl_pending = 1;
        pthread_cond_signal(&fl_cond);
    }
    pthread_mutex_unlock(&fl_lock);
    stat_rendered++;

    int health = (gamestate == GS_LEVEL && players[consoleplayer].mo) ? players[consoleplayer].health : -1;
    leds_update(health);

    static uint32_t last_log;
    uint32_t now = DG_GetTicksMs();
    if (now - last_log >= 5000) {
        if (last_log) {
            float s = (now - last_log) / 1000.0f;
            logm("%.1f/s drawn by the engine, %.1f/s flushed to the panel, %.1f/s superseded", stat_rendered / s, __atomic_load_n(&stat_flushed, __ATOMIC_RELAXED) / s, stat_replaced / s);
        }
        last_log = now; stat_rendered = 0; stat_replaced = 0; __atomic_store_n(&stat_flushed, 0, __ATOMIC_RELAXED);
    }
}

void DG_SetWindowTitle(const char *title) { logm("%s", title); }

int main(int argc, char **argv)
{
    doomgeneric_Create(argc, argv);
    for (;;) doomgeneric_Tick();
    return 0;
}
