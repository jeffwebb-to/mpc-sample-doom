/*
 * doomgeneric platform layer for the Akai MPC Sample (AC50).
 *
 * Screen:  /dev/dri/card0 as DRM master (the stock app must be stopped), one dumb buffer
 *          320x240 XRGB8888 scanned out with SETCRTC. The game's 320x200 frame is copied
 *          into a RAM frame by the game thread and pushed to the panel by a flush thread
 *          (copy into the dumb buffer + DIRTYFB of the game rectangle). The panel is an SPI
 *          mipi-dbi display: it only updates on DIRTYFB, and a flush blocks the caller for
 *          tens of ms on real hardware, so the game thread never flushes itself. If a new
 *          frame arrives while the flush thread is busy it replaces the waiting one, so
 *          there is never more than one frame of lag.
 * Input:   the control surface is a raw MIDI device (/dev/snd/midiC<n>D0, card id "Surface").
 *          A reader thread parses pads (channel 10), buttons (channel 1) and the DATA
 *          encoder (CC 100, relative) into a key queue the game thread drains in DG_GetKey.
 *          The encoder turns the player through a mouse event (proportional), or moves the
 *          menu cursor while a menu is open.
 * LEDs:    pads 1-8 show their role in colour; pads 9-16 are a health bar.
 * Splash:  a title card (src/splash.h, generated by tools/mksplash.py) is drawn as soon as
 *          the panel is ours and stays until the engine has loaded and drawn its first frame.
 *
 * Copyright (C) 2026 Jeff Webb (jeffwebb-to). GPL-2.0, like the engine.
 */
