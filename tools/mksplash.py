#!/usr/bin/env python3
"""Render the boot splash text to src/splash.h as a 1-bit bitmap.

Run this after changing LINES. It uses Pillow's built-in font (Aileron, CC0), so the
output does not depend on the fonts installed on the machine. The C side paints each
line in its own colour; the header records which rows belong to which line.
"""
import os, sys
from PIL import Image, ImageDraw, ImageFont

W, H = 320, 240
# text, point size, stroke width (fake bold)
LINES = [
    ("MPC DOOM", 44, 1),
    ("by Jeff Webb (LeBaron James)", 17, 0),
    ("github jeffwebb-to", 17, 0),
]
GAP = 10          # pixels between lines
TOP_MARGIN = 20   # keep everything inside the 320x200 game area (rows 20..219)

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "splash.h")
img = Image.new("1", (W, H), 0)
draw = ImageDraw.Draw(img)

rendered = []
for text, size, stroke in LINES:
    font = ImageFont.load_default(size=size)
    l, t, r, b = draw.textbbox((0, 0), text, font=font, stroke_width=stroke)
    rendered.append((text, font, stroke, r - l, b - t, l, t))

total = sum(h for *_, h, _, _ in rendered) + GAP * (len(rendered) - 1)
y = TOP_MARGIN + (200 - total) // 2
rows = []
for text, font, stroke, w, h, l, t in rendered:
    x = (W - w) // 2
    draw.text((x - l, y - t), text, font=font, fill=1, stroke_width=stroke, stroke_fill=1)
    rows.append((y, y + h))
    y += h + GAP

y0, y1 = rows[0][0], rows[-1][1]
assert y0 >= 20 and y1 <= 220, (y0, y1)
px = img.load()
with open(out, "w") as f:
    f.write("/* Generated by tools/mksplash.py, do not edit. 1 bit per pixel, MSB first, %d bytes per row. */\n" % (W // 8))
    f.write("#define SPLASH_Y0 %d\n#define SPLASH_H %d\n#define SPLASH_LINES %d\n" % (y0, y1 - y0, len(rows)))
    f.write("static const int splash_line_end[SPLASH_LINES] = { %s };  /* row after each line, relative to SPLASH_Y0 */\n"
            % ", ".join(str(b - y0) for a, b in rows))
    f.write("static const unsigned char splash_bits[SPLASH_H][%d] = {\n" % (W // 8))
    for yy in range(y0, y1):
        bytes_ = []
        for bx in range(W // 8):
            v = 0
            for bit in range(8):
                if px[bx * 8 + bit, yy]:
                    v |= 0x80 >> bit
            bytes_.append("0x%02X" % v)
        f.write("    { %s },\n" % ", ".join(bytes_))
    f.write("};\n")
if "--preview" in sys.argv:
    img.save(sys.argv[sys.argv.index("--preview") + 1])
print("wrote", os.path.normpath(out), "rows", y0, "to", y1)
